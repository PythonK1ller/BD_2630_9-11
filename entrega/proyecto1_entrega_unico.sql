    -- 40 edificios.
    FOR id_edificio IN 1 .. edificios.COUNT LOOP
        INSERT INTO edificio (id, nombre)
        VALUES (id_edificio, edificios(id_edificio));
    END LOOP;

    -- 200 pisos: cada grupo de cinco edificios tiene 4, 5, 5, 5 y 6 pisos.
    FOR id_edificio IN 1 .. edificios.COUNT LOOP
        cantidad_pisos := CASE MOD(id_edificio, 5)
                              WHEN 1 THEN 4
                              WHEN 0 THEN 6
                              ELSE 5
                          END;

        FOR numero_piso IN 1 .. cantidad_pisos LOOP
            id_piso := id_piso + 1;
            INSERT INTO piso (id, numeropiso, idedificio)
            VALUES (id_piso, numero_piso, id_edificio);
        END LOOP;
    END LOOP;

