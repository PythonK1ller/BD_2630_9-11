-- Metas incumplidas y perdida monetaria.
CREATE OR REPLACE VIEW vista_1 AS
SELECT c.nombre AS colaborador,
       c.vinculacion,
       f.nombre AS cafeteria,
       e.nombre AS edificio,
       m.fechameta AS fecha_meta,
       m.valormeta AS valor_meta,
       m.valorreal AS valor_real,
       m.valormeta - m.valorreal AS perdida_monetaria
  FROM meta m
  JOIN colaborador c ON c.id = m.idcolaborador
  JOIN cafeteria f ON f.id = m.idcafeteria
  JOIN piso p ON p.id = f.idpiso
  JOIN edificio e ON e.id = p.idedificio
 WHERE m.valorreal < m.valormeta
 ORDER BY perdida_monetaria DESC, fecha_meta DESC;

-- Cantidad de cafeterias por piso, incluyendo los pisos con cero cafeterias.
CREATE OR REPLACE VIEW vista_2 AS
SELECT e.nombre AS edificio,
       p.numeropiso AS numero_piso,
       COUNT(f.id) AS total_cafeterias
  FROM edificio e
  JOIN piso p ON p.idedificio = e.id
  LEFT JOIN cafeteria f ON f.idpiso = p.id
 GROUP BY e.id, e.nombre, p.numeropiso
 ORDER BY e.nombre, p.numeropiso;

-- Comision por vinculacion y anio, mas el total general.
CREATE OR REPLACE VIEW vista_3 AS
SELECT NVL(c.vinculacion, 'TOTAL GENERAL') AS vinculacion,
       NVL(TO_CHAR(EXTRACT(YEAR FROM m.fechameta)), 'TODOS') AS anio,
       SUM(m.valorreal * c.comision / 100) AS total_comision
  FROM meta m
  JOIN colaborador c ON c.id = m.idcolaborador
 GROUP BY GROUPING SETS (
     (c.vinculacion, EXTRACT(YEAR FROM m.fechameta)),
     ()
 )
 ORDER BY GROUPING(c.vinculacion), c.vinculacion,
          EXTRACT(YEAR FROM m.fechameta);

-- Meses en los que el promedio real de la cafeteria supera su promedio meta.
CREATE OR REPLACE VIEW vista_4 AS
SELECT EXTRACT(YEAR FROM m.fechameta) AS anio,
       EXTRACT(MONTH FROM m.fechameta) AS mes,
       f.nombre AS cafeteria,
       ROUND(AVG(m.valorreal), 2) AS promedio_ventas_reales,
       ROUND(AVG(m.valormeta), 2) AS promedio_metas
  FROM meta m
  JOIN cafeteria f ON f.id = m.idcafeteria
 GROUP BY EXTRACT(YEAR FROM m.fechameta),
          EXTRACT(MONTH FROM m.fechameta),
          f.id, f.nombre
HAVING AVG(m.valorreal) > AVG(m.valormeta)
 ORDER BY anio, mes, cafeteria;

-- Colaboradores cuyo total historico supera el promedio de los totales.
CREATE OR REPLACE VIEW vista_5 AS
WITH totales AS (
    SELECT c.id,
           c.nombre,
           SUM(m.valorreal) AS total_ventas_reales
      FROM colaborador c
      JOIN meta m ON m.idcolaborador = c.id
     GROUP BY c.id, c.nombre
), promedio AS (
    SELECT AVG(total_ventas_reales) AS valor
      FROM totales
)
SELECT t.nombre AS colaborador,
       t.total_ventas_reales,
       ROUND(p.valor, 2) AS promedio_general
  FROM totales t
 CROSS JOIN promedio p
 WHERE t.total_ventas_reales > p.valor
 ORDER BY t.total_ventas_reales DESC;

-- Colaboradores presentes en todos los edificios que tienen cafeterias.
CREATE OR REPLACE VIEW vista_6 AS
SELECT c.nombre AS colaborador,
       c.numerodocumento AS numero_documento
  FROM colaborador c
  JOIN meta m ON m.idcolaborador = c.id
  JOIN cafeteria f ON f.id = m.idcafeteria
  JOIN piso p ON p.id = f.idpiso
 GROUP BY c.id, c.nombre, c.numerodocumento
HAVING COUNT(DISTINCT p.idedificio) = (
    SELECT COUNT(DISTINCT p2.idedificio)
      FROM cafeteria f2
      JOIN piso p2 ON p2.id = f2.idpiso
)
 ORDER BY c.nombre;

-- Colaboradores distintos por edificio y tipo de vinculacion.
CREATE OR REPLACE VIEW vista_7 AS
SELECT NVL(e.nombre, 'TOTALES') AS edificio,
       COUNT(DISTINCT CASE WHEN c.vinculacion = 'PLANTA' THEN c.id END)
           AS colaboradores_planta,
       COUNT(DISTINCT CASE WHEN c.vinculacion = 'TEMPORAL' THEN c.id END)
           AS colaboradores_temporales,
       COUNT(DISTINCT c.id) AS total
  FROM edificio e
  JOIN piso p ON p.idedificio = e.id
  JOIN cafeteria f ON f.idpiso = p.id
  JOIN meta m ON m.idcafeteria = f.id
  JOIN colaborador c ON c.id = m.idcolaborador
 GROUP BY GROUPING SETS ((e.id, e.nombre), ())
 ORDER BY GROUPING(e.nombre), e.nombre;

