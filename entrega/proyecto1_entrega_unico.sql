        'Claudia Patricia León', 'Ricardo Alonso Mejía', 'Mónica Alejandra Peña',
        'Fernando José Cárdenas', 'Adriana Lucía Ospina', 'Camilo Ernesto Rojas',
        'Gloria Esperanza Niño', 'Héctor Mauricio Salazar',
        'Liliana Beatriz Cortés', 'Sebastián Quintero', 'Yolanda Marcela Pineda',
        'Alejandro Bermúdez', 'Verónica Isabel Duarte', 'Nicolás Esteban Guzmán');

    ---------------------------------------------------------------- parametros
    c_fecha_inicio  CONSTANT DATE := DATE '2025-09-01';
    c_fecha_fin     CONSTANT DATE := DATE '2026-02-28';
    c_semilla       CONSTANT NUMBER := 20261;

    ------------------------------------------------------------------ trabajo
    v_id_piso    PLS_INTEGER := 0;
    v_num_pisos  PLS_INTEGER;
    v_idpiso     NUMBER;
    v_id_meta    PLS_INTEGER := 0;
    v_fecha      DATE;
    v_paso       PLS_INTEGER;
    v_base       NUMBER;
    v_factor     NUMBER;
    v_real       NUMBER;
    v_mes        PLS_INTEGER;
BEGIN
    DBMS_RANDOM.SEED(c_semilla);

    ----------------------------------------------------------------- EDIFICIO
    FOR i IN 1 .. v_edificios.COUNT LOOP
        INSERT INTO edificio (id, nombre) VALUES (i, v_edificios(i));
    END LOOP;

    --------------------------------------------------------------------- PISO
    -- Cantidad de pisos por edificio segun i MOD 5: 4, 5, 5, 5 o 6.
    -- El numero de piso reinicia en 1 en cada edificio, como exige el enunciado.
    FOR i IN 1 .. v_edificios.COUNT LOOP
        v_num_pisos := CASE MOD(i, 5)
                           WHEN 1 THEN 4
                           WHEN 0 THEN 6
                           ELSE 5
                       END;
        FOR n IN 1 .. v_num_pisos LOOP
            v_id_piso := v_id_piso + 1;
            INSERT INTO piso (id, numeropiso, idedificio)
                 VALUES (v_id_piso, n, i);
        END LOOP;
    END LOOP;

    ---------------------------------------------------------------- CAFETERIA
    -- El id del piso no se conoce de antemano: se resuelve por la llave natural
    -- (numeropiso, idedificio), que es justamente para lo que existe.
    FOR i IN 1 .. v_caf_nombre.COUNT LOOP
        SELECT id
          INTO v_idpiso
          FROM piso
         WHERE idedificio = v_caf_edificio(i)
           AND numeropiso = v_caf_piso(i);

        INSERT INTO cafeteria (id, nombre, idpiso)
             VALUES (i, v_caf_nombre(i), v_idpiso);
    END LOOP;

    -------------------------------------------------------------- COLABORADOR
    FOR i IN 1 .. v_colaboradores.COUNT LOOP
        INSERT INTO colaborador (id, nombre, tipodocumento, numerodocumento,
                                 vinculacion, comision)
             VALUES (i,
                     v_colaboradores(i),
                     CASE WHEN MOD(i, 7) = 0 THEN 'CE' ELSE 'CC' END,
                     1000000000 + MOD(i * 1234567, 900000000),
                     CASE WHEN MOD(i, 3) = 0 THEN 'TEMPORAL' ELSE 'PLANTA' END,
                     CASE MOD(i, 4) WHEN 0 THEN 15
                                    WHEN 1 THEN 10
                                    WHEN 2 THEN 8
                                    ELSE 12 END);
    END LOOP;

    --------------------------------------------------------------------- META
    -- Para cada par (colaborador, cafeteria) se recorre el periodo dando saltos
    -- de v_paso dias desde un desfase distinto por par. Al ser fechas
    -- estrictamente crecientes dentro de cada par, la llave natural
    -- (idcolaborador, idcafeteria, fechameta) NO se puede repetir: no hace falta
    -- verificar duplicados ni manejar DUP_VAL_ON_INDEX.
    FOR c IN 1 .. v_colaboradores.COUNT LOOP

        -- Colaboradores 25 y 26: sin ninguna meta (requisito del enunciado).
        CONTINUE WHEN c IN (25, 26);

        FOR f IN 1 .. v_caf_nombre.COUNT LOOP

            -- Colaboradores 1 a 5: cobertura total (las 12 cafeterias).
            -- El resto: solo 3 cafeterias cada uno.
            CONTINUE WHEN c > 5 AND MOD(f + c, 4) <> 0;

            -- El paso es impar a proposito: con un paso multiplo de 7 (14, 21)
            -- todas las fechas del par caerian siempre en el mismo dia de la
            -- semana y los pares que arrancaran en domingo se quedarian sin
            -- ninguna meta.
            v_paso  := CASE WHEN c <= 5 THEN 24 ELSE 13 END;
            v_fecha := c_fecha_inicio + MOD(c * 3 + f * 5, 7);

            WHILE v_fecha <= c_fecha_fin LOOP
                -- Las cafeterias no operan los domingos.
                IF TO_CHAR(v_fecha, 'D', 'NLS_TERRITORY=AMERICA') <> '1' THEN

                    v_base := (200 + TRUNC(DBMS_RANDOM.VALUE(0, 701))) * 1000;
                    v_mes  := EXTRACT(MONTH FROM v_fecha);

                    -- Noviembre y febrero: meses malos, casi todo se incumple.
                    v_factor := CASE
                                    WHEN v_mes IN (11, 2) THEN DBMS_RANDOM.VALUE(0.55, 0.95)
                                    WHEN v_mes IN (9, 1)  THEN DBMS_RANDOM.VALUE(0.70, 1.15)
                                    ELSE                       DBMS_RANDOM.VALUE(0.85, 1.35)
                                END;

                    v_real    := TRUNC(v_base * v_factor / 1000) * 1000;
                    v_id_meta := v_id_meta + 1;

                    INSERT INTO meta (id, fechameta, valormeta, valorreal,
                                      idcafeteria, idcolaborador)
                         VALUES (v_id_meta, v_fecha, v_base, v_real, f, c);
                END IF;

                v_fecha := v_fecha + v_paso;
            END LOOP;
        END LOOP;
    END LOOP;

    ------------------------------------------------- resincronizar identities
    -- Los id se insertaron de forma explicita, asi que la secuencia interna de
    -- cada columna IDENTITY sigue en 1. Se reposiciona en el maximo existente
    -- para que un INSERT posterior que omita el id no choque con la PK.
    EXECUTE IMMEDIATE 'ALTER TABLE edificio    MODIFY (id GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE))';
    EXECUTE IMMEDIATE 'ALTER TABLE piso        MODIFY (id GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE))';
    EXECUTE IMMEDIATE 'ALTER TABLE cafeteria   MODIFY (id GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE))';
    EXECUTE IMMEDIATE 'ALTER TABLE colaborador MODIFY (id GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE))';
    EXECUTE IMMEDIATE 'ALTER TABLE meta        MODIFY (id GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE))';

    COMMIT;

    DBMS_OUTPUT.PUT_LINE('Poblamiento terminado:');
    DBMS_OUTPUT.PUT_LINE('  edificios    : ' || v_edificios.COUNT);
    DBMS_OUTPUT.PUT_LINE('  pisos        : ' || v_id_piso);
    DBMS_OUTPUT.PUT_LINE('  cafeterias   : ' || v_caf_nombre.COUNT);
    DBMS_OUTPUT.PUT_LINE('  colaboradores: ' || v_colaboradores.COUNT);
    DBMS_OUTPUT.PUT_LINE('  metas        : ' || v_id_meta);

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        DBMS_OUTPUT.PUT_LINE('Error en el poblamiento: ' || SQLERRM);
        RAISE;
END;
/

-- ############################ sql/03_vistas/vista_1.sql ############################

--------------------------------------------------------------------------------
-- VISTA_1 - [10] Listado de incumplimientos de metas
--
-- Colaborador, vinculacion, cafeteria, edificio, fecha, meta, real y la perdida
-- monetaria (meta - real), solo para los registros donde el valor real quedo
-- estrictamente por debajo de la meta.
-- Orden: perdida descendente y luego fecha descendente.
--------------------------------------------------------------------------------

CREATE OR REPLACE VIEW vista_1 AS
SELECT col.nombre                        AS colaborador,
       col.vinculacion                   AS vinculacion,
       caf.nombre                        AS cafeteria,
       edi.nombre                        AS edificio,
       met.fechameta                     AS fecha_meta,
       met.valormeta                     AS valor_meta,
       met.valorreal                     AS valor_real,
       met.valormeta - met.valorreal     AS perdida_monetaria
  FROM meta         met
  JOIN colaborador  col ON col.id = met.idcolaborador
  JOIN cafeteria    caf ON caf.id = met.idcafeteria
  JOIN piso         pis ON pis.id = caf.idpiso
  JOIN edificio     edi ON edi.id = pis.idedificio
 WHERE met.valorreal < met.valormeta
 ORDER BY perdida_monetaria DESC,
          met.fechameta     DESC;
/

-- ############################ sql/03_vistas/vista_2.sql ############################

--------------------------------------------------------------------------------
-- VISTA_2 - [10] Cobertura de infraestructura
--
-- Cantidad de cafeterias por piso. Los pisos sin cafeteria deben aparecer con 0,
-- por eso el LEFT JOIN va desde PISO hacia CAFETERIA y se cuenta caf.id (no *):
-- COUNT(*) contaria la fila del piso aunque no exista cafeteria y devolveria 1.
--------------------------------------------------------------------------------

CREATE OR REPLACE VIEW vista_2 AS
SELECT edi.nombre        AS edificio,
       pis.numeropiso    AS numero_piso,
       COUNT(caf.id)     AS total_cafeterias
  FROM edificio   edi
  JOIN piso       pis ON pis.idedificio = edi.id
  LEFT JOIN cafeteria caf ON caf.idpiso = pis.id
 GROUP BY edi.id, edi.nombre, pis.numeropiso
 ORDER BY edi.nombre, pis.numeropiso;
/

-- ############################ sql/03_vistas/vista_3.sql ############################

--------------------------------------------------------------------------------
-- VISTA_3 - [10] Proyeccion de comisiones por tipo de contrato
--
-- Total a pagar por comisiones agrupado por vinculacion y ano, mas una fila
-- final con el gran total general.
--
-- La comision es un porcentaje que se paga SOBRE LAS VENTAS REALES:
--     comision = valorreal * (comision / 100)
--
-- Se usa GROUP BY GROUPING SETS y no ROLLUP: ROLLUP agregaria ademas un
-- subtotal por cada vinculacion, y el enunciado solo pide los grupos
-- (vinculacion, ano) y el gran total. GROUPING() se usa en el ORDER BY para
-- forzar que la fila del total quede de ultima.
--------------------------------------------------------------------------------

CREATE OR REPLACE VIEW vista_3 AS
SELECT NVL(col.vinculacion, 'TOTAL GENERAL')                       AS vinculacion,
       NVL(TO_CHAR(EXTRACT(YEAR FROM met.fechameta)), 'TODOS')     AS anio,
       SUM(met.valorreal * col.comision / 100)                     AS total_comision
  FROM meta        met
  JOIN colaborador col ON col.id = met.idcolaborador
 GROUP BY GROUPING SETS ( (col.vinculacion, EXTRACT(YEAR FROM met.fechameta)),
                          () )
 ORDER BY GROUPING(col.vinculacion),
          col.vinculacion,
          EXTRACT(YEAR FROM met.fechameta);
/

-- ############################ sql/03_vistas/vista_4.sql ############################

--------------------------------------------------------------------------------
-- VISTA_4 - [10] Rendimiento mensual por cafeteria
--
-- Ano, mes, cafeteria y promedio de ventas reales diarias, mostrando unicamente
-- las combinaciones (cafeteria, ano, mes) donde ese promedio supero el promedio
-- de las metas propuestas para el mismo mes.
--
-- La comparacion entre los dos promedios va en HAVING porque involucra dos
-- funciones de agregacion del mismo grupo; no puede ir en WHERE.
--------------------------------------------------------------------------------

CREATE OR REPLACE VIEW vista_4 AS
SELECT EXTRACT(YEAR  FROM met.fechameta)  AS anio,
       EXTRACT(MONTH FROM met.fechameta)  AS mes,
       caf.nombre                         AS cafeteria,
       ROUND(AVG(met.valorreal), 2)       AS promedio_ventas_reales,
       ROUND(AVG(met.valormeta), 2)       AS promedio_metas
  FROM meta      met
  JOIN cafeteria caf ON caf.id = met.idcafeteria
 GROUP BY EXTRACT(YEAR FROM met.fechameta),
          EXTRACT(MONTH FROM met.fechameta),
          caf.id,
          caf.nombre
HAVING AVG(met.valorreal) > AVG(met.valormeta)
 ORDER BY anio, mes, cafeteria;
/

-- ############################ sql/03_vistas/vista_5.sql ############################

--------------------------------------------------------------------------------
-- VISTA_5 - [10] Top de colaboradores sobre el promedio
--
-- Colaboradores cuyo total historico de ventas reales supera el promedio general
-- de ventas de todos los colaboradores. Se lista el nombre, su total y, como
-- tercera columna, el promedio general para poder contrastar.
--
-- Interpretacion del "promedio general": es el promedio de los TOTALES por
-- colaborador, no el promedio de los registros individuales de META. Por eso se
-- calcula primero el total de cada colaborador (CTE totales) y sobre ese
-- resultado se saca el AVG.
--------------------------------------------------------------------------------

CREATE OR REPLACE VIEW vista_5 AS
WITH totales AS (
    SELECT col.id                AS id_colaborador,
           col.nombre            AS nombre,
           SUM(met.valorreal)    AS total_ventas_reales
      FROM colaborador col
      JOIN meta        met ON met.idcolaborador = col.id
     GROUP BY col.id, col.nombre
)
SELECT tot.nombre                                        AS colaborador,
       tot.total_ventas_reales                           AS total_ventas_reales,
       (SELECT ROUND(AVG(total_ventas_reales), 2) FROM totales) AS promedio_general
  FROM totales tot
 WHERE tot.total_ventas_reales > (SELECT AVG(total_ventas_reales) FROM totales)
 ORDER BY tot.total_ventas_reales DESC;
/

-- ############################ sql/03_vistas/vista_6.sql ############################

--------------------------------------------------------------------------------
-- VISTA_6 - [10] Cobertura total de edificios
--
-- Colaboradores con registros de metas en cafeterias de todos los edificios.
--
-- IMPORTANTE (decision de diseno):
-- El enunciado exige, en la seccion de insercion de datos, que existan al menos
-- dos edificios SIN ninguna cafeteria asociada. Si "todos los edificios" se
-- interpretara literalmente como los 40 registros de EDIFICIO, ningun
-- colaborador podria cumplirlo jamas (no hay cafeteria alli donde tener una
-- meta) y la vista quedaria vacia, contradiciendo la nota final "asegurese que
-- todas las consultas tengan tuplas de resultado".
--
-- Por eso el universo de comparacion son los edificios QUE TIENEN AL MENOS UNA
-- CAFETERIA: es la unica lectura bajo la cual la consulta es satisfacible.
-- La subconsulta escalar calcula ese universo de forma dinamica, sin constantes
-- quemadas, de modo que la vista sigue siendo correcta si cambian los datos.
--------------------------------------------------------------------------------

CREATE OR REPLACE VIEW vista_6 AS
SELECT col.nombre           AS colaborador,
       col.tipodocumento    AS tipo_documento,
       col.numerodocumento  AS numero_documento
  FROM colaborador col
  JOIN meta        met ON met.idcolaborador = col.id
  JOIN cafeteria   caf ON caf.id = met.idcafeteria
  JOIN piso        pis ON pis.id = caf.idpiso
 GROUP BY col.id, col.nombre, col.tipodocumento, col.numerodocumento
HAVING COUNT(DISTINCT pis.idedificio) = ( SELECT COUNT(DISTINCT pis2.idedificio)
                                            FROM cafeteria caf2
                                            JOIN piso      pis2 ON pis2.id = caf2.idpiso )
 ORDER BY col.nombre;
/

-- ############################ sql/03_vistas/vista_7.sql ############################

--------------------------------------------------------------------------------
-- VISTA_7 - [20] Colaboradores por edificio y tipo de vinculacion
--
--   Edificio | Colaboradores de planta | Colaboradores temporales | Total
--   Barón    |            3            |            2             |   5
--   Giraldo  |            4            |            2             |   6
--   ...
--   Totales  |            7            |            4             |  11
--
-- Un colaborador "esta" en un edificio si tiene al menos una meta registrada en
-- alguna cafeteria ubicada en ese edificio. Se cuenta DISTINCT sobre col.id
-- porque un mismo colaborador tiene muchas metas en el mismo edificio y no debe
-- contarse varias veces.
--
-- La tabulacion cruzada se arma con COUNT(DISTINCT CASE WHEN ...): el CASE deja
-- NULL cuando la vinculacion no corresponde y COUNT ignora los NULL.
--
-- OJO con la fila de totales: al ser un COUNT DISTINCT global, un colaborador
-- que trabaja en dos edificios se cuenta UNA sola vez. Por eso la fila "TOTALES"
-- puede ser menor que la suma vertical de las filas anteriores. Es el
-- comportamiento correcto (son colaboradores distintos, no una sumatoria).
--------------------------------------------------------------------------------

CREATE OR REPLACE VIEW vista_7 AS
SELECT NVL(edi.nombre, 'TOTALES')                                              AS edificio,
       COUNT(DISTINCT CASE WHEN col.vinculacion = 'PLANTA'   THEN col.id END)  AS colaboradores_planta,
       COUNT(DISTINCT CASE WHEN col.vinculacion = 'TEMPORAL' THEN col.id END)  AS colaboradores_temporales,
       COUNT(DISTINCT col.id)                                                  AS total
  FROM edificio    edi
  JOIN piso        pis ON pis.idedificio   = edi.id
  JOIN cafeteria   caf ON caf.idpiso       = pis.id
  JOIN meta        met ON met.idcafeteria  = caf.id
  JOIN colaborador col ON col.id           = met.idcolaborador
 GROUP BY GROUPING SETS ( (edi.id, edi.nombre), () )
 ORDER BY GROUPING(edi.nombre),
          edi.nombre;
/

-- ############################ sql/04_permisos/01_grants.sql ############################

