    FOR id_cafeteria IN 1 .. cafeterias.COUNT LOOP
        SELECT id
          INTO piso_encontrado
          FROM piso
         WHERE idedificio = edificio_cafeteria(id_cafeteria)
           AND numeropiso = piso_cafeteria(id_cafeteria);

        INSERT INTO cafeteria (id, nombre, idpiso)
        VALUES (id_cafeteria, cafeterias(id_cafeteria), piso_encontrado);
    END LOOP;

    -- 26 colaboradores: cada tercero es temporal; los demas son de planta.
    FOR id_colaborador IN 1 .. colaboradores.COUNT LOOP
        INSERT INTO colaborador (
            id, nombre, tipodocumento, numerodocumento, vinculacion, comision
        ) VALUES (
            id_colaborador,
            colaboradores(id_colaborador),
            CASE WHEN MOD(id_colaborador, 7) = 0 THEN 'CE' ELSE 'CC' END,
            10000000 + MOD(id_colaborador * 12345, 9000000),
            CASE WHEN MOD(id_colaborador, 3) = 0 THEN 'TEMPORAL' ELSE 'PLANTA' END,
            CASE MOD(id_colaborador, 4)
                WHEN 0 THEN 15
                WHEN 1 THEN 10
                WHEN 2 THEN 8
                ELSE 12
            END
        );
    END LOOP;

    -- Los colaboradores 25 y 26 quedan sin metas.
    FOR id_colaborador IN 1 .. colaboradores.COUNT LOOP
        CONTINUE WHEN id_colaborador IN (25, 26);

        FOR id_cafeteria IN 1 .. cafeterias.COUNT LOOP
            -- Los colaboradores 1 a 5 cubren todas las cafeterias.
            CONTINUE WHEN id_colaborador > 5
                      AND MOD(id_cafeteria + id_colaborador, 4) <> 0;

            salto_dias := CASE WHEN id_colaborador <= 5 THEN 24 ELSE 13 END;
            fecha_meta := fecha_inicio + MOD(id_colaborador * 3 + id_cafeteria * 5, 7);

            WHILE fecha_meta <= fecha_fin LOOP
                IF TO_CHAR(fecha_meta, 'DY', 'NLS_DATE_LANGUAGE=ENGLISH') <> 'SUN' THEN
