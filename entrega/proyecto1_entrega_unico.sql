                        id, fechameta, valormeta, valorreal, idcafeteria, idcolaborador
                    ) VALUES (
                        id_meta, fecha_meta, valor_meta, valor_real,
                        id_cafeteria, id_colaborador
                    );
                END IF;

                fecha_meta := fecha_meta + salto_dias;
            END LOOP;
        END LOOP;
    END LOOP;

