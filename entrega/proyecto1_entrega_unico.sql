        'Liliana Beatriz Cortés', 'Sebastián Quintero', 'Yolanda Marcela Pineda',
        'Alejandro Bermúdez', 'Verónica Isabel Duarte', 'Nicolás Esteban Guzmán'
    );

    fecha_inicio CONSTANT DATE := DATE '2025-09-01';
    fecha_fin    CONSTANT DATE := DATE '2026-02-28';

    id_piso          PLS_INTEGER := 0;
    cantidad_pisos   PLS_INTEGER;
    piso_encontrado  NUMBER;
    id_meta          PLS_INTEGER := 0;
    fecha_meta       DATE;
    salto_dias       PLS_INTEGER;
    valor_meta       NUMBER;
    porcentaje_real  NUMBER;
    valor_real       NUMBER;
