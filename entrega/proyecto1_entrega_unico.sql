    TYPE t_numero IS TABLE OF NUMBER;

    ---------------------------------------------------------------- catalogos
    v_edificios t_texto := t_texto(
        'Barón', 'Giraldo', 'Fernando Barón', 'Emilio Arango',
        'José Rafael Arboleda', 'Jesús María Fernández', 'Rafael Arboleda',
